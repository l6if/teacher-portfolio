// ═══ التثبيت الذاتي (Idempotent) ═══════════════════════════════════════
// يُنشئ/يُحدّث العناصر الرسمية فقط — بلا deleteMany إطلاقًا ولا يمس
// أي عنصر مخصص أو بيانات مستخدمين. آمن للتشغيل المتكرر والمتزامن
// (upsert بواسطة officialCode الفريد).

export interface EnsureResult {
  created: { domains: number; criteria: number; subCriteria: number }
  updated: { domains: number; criteria: number; subCriteria: number }
  totals: { domains: number; criteria: number; subCriteria: number }
}

/**
 * يضمن وجود البناء الرسمي كاملًا ومُحدَّثًا من المصدر المعتمد.
 * يُستدعى من سكربت التثبيت ومن مسار API الإطار (تثبيت ذاتي كسول
 * عند أول طلب — يضمن جاهزية الإنتاج دون خطوات يدوية).
 */
export async function ensureOfficialFramework(db: PrismaClient): Promise<EnsureResult> {
  const before = {
    domains: await db.domain.count({ where: { isOfficial: true } }),
    criteria: await db.criterion.count({ where: { isOfficial: true } }),
    subCriteria: await db.subCriterion.count({ where: { isOfficial: true } }),
  }
  const result: EnsureResult = {
    created: { domains: 0, criteria: 0, subCriteria: 0 },
    updated: { domains: 0, criteria: 0, subCriteria: 0 },
    totals: { domains: 0, criteria: 0, subCriteria: 0 },
  }

  let domainSort = 0
  for (const domain of OFFICIAL_DOMAINS) {
    domainSort += 1
    const domainRow = await db.domain.upsert({
      where: { officialCode: domain.code },
      update: {
        name: domain.name,
        description: domain.description,
        sortOrder: domainSort,
        isOfficial: true,
        scope: 'GLOBAL',
      },
      create: {
        name: domain.name,
        description: domain.description,
        isOfficial: true,
        officialCode: domain.code,
        sortOrder: domainSort,
        scope: 'GLOBAL',
      },
    })

    let criterionSort = 0
    for (const criterion of domain.criteria) {
      criterionSort += 1
      const criterionRow = await db.criterion.upsert({
        where: { officialCode: criterion.code },
        update: {
          name: criterion.name,
          description: criterion.description,
          domainId: domainRow.id,
          sortOrder: criterionSort,
          isOfficial: true,
        },
        create: {
          name: criterion.name,
          description: criterion.description,
          domainId: domainRow.id,
          isOfficial: true,
          officialCode: criterion.code,
          sortOrder: criterionSort,
        },
      })

      let subSort = 0
      for (const sub of criterion.subs) {
        subSort += 1
        await db.subCriterion.upsert({
          where: { officialCode: sub.code },
          update: {
            name: sub.name,
            criterionId: criterionRow.id,
            sortOrder: subSort,
            isOfficial: true,
          },
          create: {
            name: sub.name,
            criterionId: criterionRow.id,
            isOfficial: true,
            officialCode: sub.code,
            sortOrder: subSort,
          },
        })
      }
    }
  }

  const after = {
    domains: await db.domain.count({ where: { isOfficial: true } }),
    criteria: await db.criterion.count({ where: { isOfficial: true } }),
    subCriteria: await db.subCriterion.count({ where: { isOfficial: true } }),
  }
  // القياس الدقيق: الجديد = الزيادة عن قبل؛ والموجود سابقًا مرّ عبر upsert (تحديث)
  result.created = {
    domains: Math.max(0, after.domains - before.domains),
    criteria: Math.max(0, after.criteria - before.criteria),
    subCriteria: Math.max(0, after.subCriteria - before.subCriteria),
  }
  result.updated = {
    domains: Math.max(0, before.domains - 0),
    criteria: Math.max(0, before.criteria - 0),
    subCriteria: Math.max(0, before.subCriteria - 0),
  }
  result.totals = after
  return result
}
